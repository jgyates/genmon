"""Generate the firmware's compiled-in copies of genmon's upstream data files.

The ESP32 has no copy of genmon's data/ directory, so the pieces the firmware
needs are compiled in. Generating them straight from the upstream files means
that after merging upstream changes, re-running this script is all it takes
to pick up new alarm codes or Home Assistant entity definitions.

Outputs (both under esp32/src/core/):
    alarm_codes_table.inc   data/ALARMS.txt as a sorted C++ array
    ha_definitions.inc      data/homeassistant/{base,generac_evo_nexus,userdefined}.json
                            as minified C++ raw string literals

Usage:
    python esp32/tools/gen_upstream_data.py [--check]

With --check nothing is written; the exit status is 1 if any output is stale,
which is how the upstream-sync skill and CI detect a forgotten regeneration.
"""

# =============================================================================
# Imports
# =============================================================================

from __future__ import annotations

import argparse
import json
import logging
import pathlib
import sys
from dataclasses import dataclass


# =============================================================================
# Constants
# =============================================================================

ESP32_ROOT  = pathlib.Path(__file__).resolve().parent.parent
REPO_ROOT   = ESP32_ROOT.parent
CORE_DIR    = ESP32_ROOT / "src" / "core"
DATA_DIR    = REPO_ROOT / "data"
HA_DATA_DIR = DATA_DIR / "homeassistant"

ALARMS_INPUT  = DATA_DIR / "ALARMS.txt"
ALARMS_OUTPUT = CORE_DIR / "alarm_codes_table.inc"
HA_OUTPUT     = CORE_DIR / "ha_definitions.inc"

# File name -> C++ identifier. A missing optional file becomes "{}".
HA_SOURCES = {
    "base.json"              : ("kHaBaseDefinitions",       True),
    "generac_evo_nexus.json" : ("kHaControllerDefinitions", True),
    "userdefined.json"       : ("kHaUserDefinitions",       False),
}

ALARM_FIELD_COUNT = 5
ALARM_FIELD_SEP   = "!"
COMMENT_PREFIX    = "#"
RAW_DELIMITER     = "GENMON"

GENERATED_NOTICE = (
    "// Generated by esp32/tools/gen_upstream_data.py from {source}.\n"
    "// Do not edit by hand; edit the upstream file and re-run the generator.\n"
)

LOGGER = logging.getLogger("gen_upstream_data")


# =============================================================================
# Types
# =============================================================================

@dataclass(frozen=True)
class AlarmEntry:
    """One line of ALARMS.txt."""

    code: int
    kind: str
    name: str
    condition: str
    info: str


# =============================================================================
# Helpers
# =============================================================================

def parse_alarm_lines(lines: list[str]) -> list[AlarmEntry]:
    """Parse ALARMS.txt lines into entries sorted by code; the first duplicate wins.

    Blank lines, comments and lines without exactly five fields are skipped,
    matching how genmon's own reader treats them.
    """
    entries: dict[int, AlarmEntry] = {}
    for line_number, raw_line in enumerate(lines, start=1):
        line = raw_line.strip()
        if not line or line.startswith(COMMENT_PREFIX):
            continue

        fields = [field.strip() for field in line.split(ALARM_FIELD_SEP)]
        if len(fields) != ALARM_FIELD_COUNT or not fields[0].isdigit():
            LOGGER.debug("skipping malformed ALARMS.txt line %d", line_number)
            continue

        entry = AlarmEntry(int(fields[0]), *fields[1:])
        if entry.code in entries:
            LOGGER.debug("duplicate alarm code %d on line %d ignored", entry.code, line_number)
            continue
        entries[entry.code] = entry

    return [entries[code] for code in sorted(entries)]


def cpp_string(text: str) -> str:
    """Return `text` as an escaped C++ string literal."""
    escaped = text.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def render_alarm_table(entries: list[AlarmEntry]) -> str:
    """Render alarm entries as initializer rows for the AlarmCode array."""
    rows = [
        f"    {{{entry.code:5d}, {cpp_string(entry.kind)}, {cpp_string(entry.name)}, "
        f"{cpp_string(entry.condition)}, {cpp_string(entry.info)}}},"
        for entry in entries
    ]
    return GENERATED_NOTICE.format(source="data/ALARMS.txt") + "\n".join(rows) + "\n"


def minified_json(path: pathlib.Path, required: bool) -> str:
    """Return the file's JSON minified, or "{}" for a missing optional file."""
    if not path.exists():
        if required:
            raise FileNotFoundError(f"required upstream file missing: {path}")
        return "{}"
    document = json.loads(path.read_text(encoding="utf-8"))
    text = json.dumps(document, separators=(",", ":"), ensure_ascii=False)
    if f"){RAW_DELIMITER}\"" in text:
        raise ValueError(f"{path} contains the raw string delimiter")
    return text


def render_ha_definitions() -> str:
    """Render the Home Assistant entity definition files as raw string literals."""
    blocks = []
    for file_name, (identifier, required) in HA_SOURCES.items():
        text = minified_json(HA_DATA_DIR / file_name, required)
        blocks.append(f'constexpr const char {identifier}[] = R"{RAW_DELIMITER}({text}){RAW_DELIMITER}";')
    notice = GENERATED_NOTICE.format(source="data/homeassistant/*.json")
    return notice + "\n" + "\n\n".join(blocks) + "\n"


def write_or_check(path: pathlib.Path, content: str, check: bool) -> bool:
    """Write `content` to `path`, or in check mode report whether it differs. Returns True if stale."""
    current = path.read_text(encoding="utf-8") if path.exists() else None
    stale   = current != content
    if check:
        if stale:
            LOGGER.error("%s is out of date with upstream data", path.relative_to(REPO_ROOT))
        return stale
    if stale:
        path.write_text(content, encoding="utf-8", newline="\n")
        LOGGER.info("updated %s", path.relative_to(REPO_ROOT))
    else:
        LOGGER.info("%s already current", path.relative_to(REPO_ROOT))
    return stale


# =============================================================================
# Entry Point
# =============================================================================

def main() -> int:
    """Regenerate (or with --check, verify) every upstream-derived file."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="verify outputs are current; write nothing")
    parser.add_argument("--verbose", action="store_true", help="log skipped ALARMS.txt lines")
    arguments = parser.parse_args()

    logging.basicConfig(
        level=logging.DEBUG if arguments.verbose else logging.INFO,
        format="%(levelname)s: %(message)s",
    )

    alarms = parse_alarm_lines(ALARMS_INPUT.read_text(encoding="utf-8").splitlines())
    LOGGER.info("%d alarm codes in %s", len(alarms), ALARMS_INPUT.relative_to(REPO_ROOT))

    stale = write_or_check(ALARMS_OUTPUT, render_alarm_table(alarms), arguments.check)
    stale = write_or_check(HA_OUTPUT, render_ha_definitions(), arguments.check) or stale

    if arguments.check and stale:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
